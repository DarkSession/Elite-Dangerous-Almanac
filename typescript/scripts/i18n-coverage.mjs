#!/usr/bin/env node

/**
 * Generate the per-dataset locale coverage table in the `i18n` barrel documentation.
 *
 * The barrel is clear that non-English locales are "intentionally sparse" and that the
 * library never manufactures an English fallback. What it could not say is *how* sparse,
 * per dataset — and the difference matters: `getModuleName` answers in German for almost
 * every module, while `getShipName` answers in German for no hull in the game. A reader
 * who only ever sees a working German example has no way to tell those apart.
 *
 * A hand-written table would state that once and then rot with the next data import, so
 * the table is generated from `data/i18n/` and checked in. `--check` re-derives it and
 * fails when the checked-in copy disagrees, which is how `check:fixtures` keeps the
 * generated fixture contracts honest.
 *
 * `DATASETS` below pairs each catalogue with its public lookup. The table values are
 * still derived from the data rather than copied by hand.
 *
 * Usage:
 *   node scripts/i18n-coverage.mjs           # rewrite the table in place
 *   node scripts/i18n-coverage.mjs --check    # fail if the table is out of date
 */

import assert from 'node:assert/strict';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { stripJsonComments } from './jsonc.mjs';

const packageRoot = fileURLToPath(new URL('../', import.meta.url));
const dataRoot = resolve(packageRoot, '..', 'data', 'i18n');
const barrel = join(packageRoot, 'src', 'i18n', 'index.ts');

/** Where the generated block starts and ends inside the barrel's TSDoc. */
const START = ' * <!-- generated by scripts/i18n-coverage.mjs -->';
const END = ' * <!-- end generated -->';

/** Locale columns, English first because it is the one that is always complete. */
const LOCALES = ['en', 'de', 'es', 'fr', 'pt', 'ru'];

const DATASETS = {
    'blueprint-names.jsonc': 'getBlueprintName',
    'experimental-effect-descriptions.jsonc': 'getExperimentalEffectDescription',
    'experimental-effect-names.jsonc': 'getExperimentalEffectName',
    'material-names.jsonc': 'getMaterialName',
    'micro-resource-names.jsonc': 'getMicroResourceName',
    'module-family-names.jsonc': 'getOutfittingFamilyName',
    'module-names.jsonc': 'getModuleName',
    'personal-modification-descriptions.jsonc': 'getPersonalModificationDescription',
    'personal-modification-names.jsonc': 'getPersonalModificationName',
    'personal-weapon-descriptions.jsonc': 'getPersonalWeaponDescription',
    'pre-engineered-variant-names.jsonc': 'getPreEngineeredVariantName',
    'suit-descriptions.jsonc': 'getSuitDescription',
    'suit-names.jsonc': 'getSuitName',
};

/**
 * Read one catalogue and count, per locale, how many of the symbols its lookup accepts
 * resolve to a stored string.
 *
 * Two shapes occur. Most files map a symbol straight to its localized values; the module
 * and pre-engineered catalogues map many symbols onto a smaller set of shared display
 * names through `nameKeys`. Counting the *symbols* in both cases is what makes the
 * columns mean the same thing everywhere: the chance that a lookup answers.
 *
 * @param file - Catalogue file name under `data/i18n/`.
 * @returns The symbol count and one percentage per locale.
 */
async function coverage(file) {
    const data = JSON.parse(stripJsonComments(await readFile(join(dataRoot, file), 'utf8')));
    const shared = data.nameKeys !== undefined && data.names !== undefined;
    const entries = shared
        ? Object.values(data.nameKeys).map((key) => data.names[key])
        : Object.values(data);
    const percent = (count) => {
        if (count === entries.length) return 100;
        if (count === 0) return 0;
        // Floor rather than round, so only a genuinely complete locale reads as 100 and
        // only a genuinely absent one reads as 0.
        return Math.max(1, Math.min(99, Math.floor((count / entries.length) * 100)));
    };
    return {
        keys: entries.length,
        percentages: LOCALES.map((locale) =>
            percent(
                entries.filter((entry) => typeof entry?.[locale] === 'string').length,
            ).toString(),
        ),
    };
}

/**
 * Render the coverage table as TSDoc comment lines.
 *
 * @returns The generated block, marker lines included.
 */
async function render() {
    const files = (await readdir(dataRoot)).filter((name) => name.endsWith('.jsonc')).sort();
    assert.deepEqual(
        files,
        Object.keys(DATASETS).sort(),
        'DATASETS must list every i18n catalogue',
    );

    const rows = [];
    for (const [file, lookup] of Object.entries(DATASETS)) {
        const { keys, percentages } = await coverage(file);
        rows.push({ lookup, keys, percentages });
    }
    // Most complete first, so a reader scanning for a usable lookup meets those first and
    // the English-only ones sit together at the bottom.
    rows.sort((left, right) => {
        const mean = (row) =>
            row.percentages.slice(1).reduce((sum, value) => sum + Number(value), 0);
        return mean(right) - mean(left) || left.lookup.localeCompare(right.lookup);
    });

    const lines = [
        START,
        ` * | Lookup | Keys | ${LOCALES.join(' | ')} |`,
        ` * | --- | ---: | ${LOCALES.map(() => '---:').join(' | ')} |`,
        ...rows.map(
            (row) => ` * | \`${row.lookup}\` | ${row.keys} | ${row.percentages.join(' | ')} |`,
        ),
        END,
    ];
    return lines.join('\n');
}

/**
 * Run the generator.
 *
 * @returns The process exit code.
 */
async function main() {
    const check = process.argv.includes('--check');
    const source = await readFile(barrel, 'utf8');
    const start = source.indexOf(START);
    const end = source.indexOf(END);
    if (start === -1 || end === -1) {
        console.error(`i18n-coverage: ${barrel} has no generated block to fill`);
        return 1;
    }
    const updated = source.slice(0, start) + (await render()) + source.slice(end + END.length);
    if (updated === source) {
        console.log('i18n-coverage: the barrel table matches data/i18n/');
        return 0;
    }
    if (check) {
        console.error(
            'i18n-coverage: the barrel table is out of date with data/i18n/ —' +
                ' run `pnpm run generate:i18n-coverage`',
        );
        return 1;
    }
    await writeFile(barrel, updated);
    console.log('i18n-coverage: rewrote the barrel table from data/i18n/');
    return 0;
}

process.exitCode = await main();
